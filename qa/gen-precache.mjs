#!/usr/bin/env node
// qa/gen-precache.mjs — keeps `site/sw.js`'s PRECACHE list equal to what is actually in `site/`.
// Dev tooling: it lives under qa/ and is never served (COMPOSED S6).
//
//   node qa/gen-precache.mjs            rewrite the list in site/sw.js (prints the diff summary)
//   node qa/gen-precache.mjs --check    exit 1 if the list is stale (what tests/sw.test.mjs asserts)
//   node qa/gen-precache.mjs --print    print the list it would write and change nothing
//
// The list is everything the browser loads: the three shell files, then every file under
// site/{css,js,data,assets}. site/sw.js itself is excluded (the browser fetches the worker outside the
// cache) and so are dotfiles (.nojekyll). BUILD-POLICY §1 means there are no scans, PNGs or fonts to
// precache, so the whole artifact fits and every screen works offline after one load.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const ROOT = join(HERE, '..');
export const SITE = join(ROOT, 'site');
export const SW_PATH = join(SITE, 'sw.js');

/** Loaded by index.html itself, in load order. */
export const SHELL_FILES = Object.freeze(['index.html', 'version.js', 'manifest.webmanifest']);
/** Every file under these directories is precached, whatever its extension. */
export const SCAN_DIRS = Object.freeze(['css', 'js', 'data', 'assets']);
/** Never listed: the worker (fetched outside the cache) and dotfiles. */
export const EXCLUDE = Object.freeze(new Set(['sw.js']));

const BEGIN = '/* === PRECACHE:BEGIN';
const END = '/* === PRECACHE:END === */';

const toPosix = (p) => p.split(sep).join('/');

function walk(dir, out = []) {
  let entries;
  try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries.sort((a, b) => (a.name < b.name ? -1 : 1))) {
    if (e.name.startsWith('.')) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.isFile()) out.push(p);
  }
  return out;
}

/**
 * buildList(siteDir = SITE) → string[] of site-relative POSIX paths, in load order:
 * the shell files (fixed order) then css, js, data, assets — each directory's files sorted.
 */
export function buildList(siteDir = SITE) {
  const out = [];
  for (const f of SHELL_FILES) {
    try { if (statSync(join(siteDir, f)).isFile()) out.push(f); } catch { /* not built yet */ }
  }
  for (const d of SCAN_DIRS) {
    for (const abs of walk(join(siteDir, d))) {
      const rel = toPosix(relative(siteDir, abs));
      if (!EXCLUDE.has(rel)) out.push(rel);
    }
  }
  return out;
}

/** The exact text of the generated block (both marker lines included). */
export function render(list) {
  const body = list.map((p) => `  '${p}',`).join('\n');
  return `${BEGIN} — generated by qa/gen-precache.mjs · run it after adding a file under site/ === */\n`
    + `const PRECACHE = [\n${body}\n];\n${END}`;
}

/** The paths currently listed in a sw.js source text (parsed from the generated block). */
export function readList(swText) {
  const i = swText.indexOf(BEGIN);
  const j = swText.indexOf(END);
  if (i < 0 || j < 0) throw new Error('site/sw.js: PRECACHE markers not found');
  return [...swText.slice(i, j).matchAll(/'([^']+)'/g)].map((m) => m[1]);
}

/** Replace the block in a sw.js source text. Returns the new text. */
export function replaceBlock(swText, list) {
  const i = swText.indexOf(BEGIN);
  const j = swText.indexOf(END);
  if (i < 0 || j < 0) throw new Error('site/sw.js: PRECACHE markers not found');
  return swText.slice(0, i) + render(list) + swText.slice(j + END.length);
}

/* ---------------- CLI ---------------- */
function main(argv) {
  const check = argv.includes('--check');
  const print = argv.includes('--print');
  const wanted = buildList();
  const text = readFileSync(SW_PATH, 'utf8');
  const current = readList(text);

  if (print) { console.log(wanted.join('\n')); return 0; }

  const added = wanted.filter((p) => !current.includes(p));
  const removed = current.filter((p) => !wanted.includes(p));
  const reordered = added.length === 0 && removed.length === 0 && current.join('\n') !== wanted.join('\n');

  if (!added.length && !removed.length && !reordered) {
    console.log(`precache list is up to date (${wanted.length} files)`);
    return 0;
  }
  if (check) {
    for (const p of added) console.error(`  missing from sw.js: ${p}`);
    for (const p of removed) console.error(`  listed but gone:    ${p}`);
    if (reordered) console.error('  list is out of order');
    console.error('run: node qa/gen-precache.mjs');
    return 1;
  }
  writeFileSync(SW_PATH, replaceBlock(text, wanted));
  for (const p of added) console.log(`  + ${p}`);
  for (const p of removed) console.log(`  - ${p}`);
  console.log(`wrote ${wanted.length} paths to site/sw.js`);
  return 0;
}

if (process.argv[1] && toPosix(process.argv[1]).endsWith('qa/gen-precache.mjs')) {
  process.exit(main(process.argv.slice(2)));
}
