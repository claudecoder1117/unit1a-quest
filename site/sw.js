/* ---------------- install: fill the version's cache ---------------- */
self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // cache.addAll() is all-or-nothing: one renamed file would abort the install and leave the student
    // with no offline app at all. Add one at a time, keep what worked, and name what did not.
    // `cache: 'reload'` skips the HTTP cache (GitHub Pages serves max-age=600) so an install after a
    // deploy stores the new bytes, not the ten-minute-old ones.
    const results = await Promise.allSettled(
      PRECACHE.map((path) => cache.add(new Request(path, { cache: 'reload' }))),
    );
    const missed = PRECACHE.filter((_, i) => results[i].status === 'rejected');
    if (missed.length) console.warn(`[sw ${CACHE}] not precached (${missed.length}):`, missed.join(', '));
  })());
  // No skipWaiting(): the new worker waits for the reload pill.
});

/* ---------------- activate: drop every older version's cache ---------------- */
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k !== CACHE && k.startsWith('packet-')).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

/* ---------------- fetch: cache-first, same-origin GET only ---------------- */
async function fromCache(request, key) {
  const cache = await caches.open(CACHE);
  return cache.match(key ?? request, { ignoreSearch: true });
}

/** Navigations always resolve to the cached shell — hash routing means every route is index.html. */
async function handleNavigate(request) {
  const shell = await fromCache(request, SHELL);
  if (shell) return shell;
  try { return await fetch(request); } catch { /* offline and not installed yet */ }
  return new Response(
    '<!doctype html><meta charset="utf-8"><title>Offline</title>' +
    '<p style="font:16px system-ui;padding:24px">The Packet is not cached on this device yet. Open it once online.</p>',
    { status: 503, headers: { 'content-type': 'text/html; charset=utf-8' } },
  );
}

async function handleAsset(request) {
  const hit = await fromCache(request);
  if (hit) return hit;
  try {
    const res = await fetch(request);
    // Only store our own complete responses: never an opaque cross-origin one, never a 404/206.
    if (res && res.ok && res.type === 'basic') {
      const copy = res.clone();
      const cache = await caches.open(CACHE);
      cache.put(request, copy).catch(() => { /* quota: the app still works online */ });
    }
    return res;
  } catch {
    if (request.destination === 'document') {
      const shell = await fromCache(request, SHELL);
      if (shell) return shell;
    }
    return new Response('', { status: 504, statusText: 'offline' });
  }
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;                       // nothing here ever POSTs
  let url;
  try { url = new URL(request.url); } catch { return; }
  if (url.origin !== self.location.origin) return;            // S6: zero third-party requests
  if (request.mode === 'navigate') { event.respondWith(handleNavigate(request)); return; }
  event.respondWith(handleAsset(request));
});

/* ---------------- messages from js/sw-register.js ---------------- */
self.addEventListener('message', (event) => {
  const data = event.data;
  const type = typeof data === 'string' ? data : (data && data.type);
  if (type === 'SKIP_WAITING') { self.skipWaiting(); return; }
  if (type === 'VERSION') {
    const reply = { type: 'VERSION', version: self.APP_VERSION, cache: CACHE, files: PRECACHE.length };
    const port = event.ports && event.ports[0];
    if (port) port.postMessage(reply);
    else if (event.source) event.source.postMessage(reply);
  }
});
