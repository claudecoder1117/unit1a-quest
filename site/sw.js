// sw.js — the offline half of "Honest and offline" (COMPOSED S9 #10). A classic worker script, NOT a
// module: it pulls in the ONE version constant with importScripts so `version.js` is the only place a
// deploy is stamped (S6), and the cache name is that constant, so bumping version.js invalidates
// everything at once and the old cache is deleted on activate.
//
// Strategy: cache-first over the whole app shell (index.html + css + js + data + assets). Everything the
// app serves is static and versioned by the cache name, so cache-first is both the fastest path and the
// offline path; a file that is somehow not in the list is fetched once and added at runtime.
//
// Update flow (S6 "Service worker update"): this worker NEVER calls skipWaiting() on its own. A new
// version installs, waits, and `js/sw-register.js` shows the "new version — reload" pill; only the
// student's tap posts {type:'SKIP_WAITING'} and reloads. Nothing swaps under a half-finished Mock.
//
// BUILD-POLICY §1: there are no scans, no PNGs and no fonts in this artifact, so there is no key
// precache and no "key not cached" state — the whole site is precached and every screen works offline.
